SELECT 3, c.Id, s.Qty, NULL, NULL, '2026-10-15', SYSUTCDATETIME(), SYSUTCDATETIME()
FROM (SELECT Code, SUM(Qty) Qty FROM #stg GROUP BY Code) s
JOIN Commodities c ON c.Code = s.Code;

