-- Upsert into EmailAccounts
MERGE dbo.EmailAccounts AS target
USING @accounts AS src
    ON LOWER(target.Email) = LOWER(src.Email)
WHEN MATCHED THEN
    UPDATE SET target.[Password] = src.[Password],
               target.IsActive = 1,
               target.UpdatedAt = SYSUTCDATETIME()
WHEN NOT MATCHED BY TARGET THEN
    INSERT (Email, [Password], DisplayName, Department, IsActive, CreatedAt)
    VALUES (src.Email, src.[Password],
            UPPER(LEFT(LEFT(src.Email, CHARINDEX('@', src.Email) - 1), 1))
              + SUBSTRING(LEFT(src.Email, CHARINDEX('@', src.Email) - 1), 2, 200),
            NULL, 1, SYSUTCDATETIME());

