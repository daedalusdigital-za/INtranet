-- ═══════════════════════════════════════════════════════════════
-- 1) UPDATE existing vehicles with correct Make/Model/VIN
-- ═══════════════════════════════════════════════════════════════
UPDATE v SET
    v.Make = f.Make,
    v.Model = f.Series,
    v.VinNumber = f.VinNumber,
    v.Status = CASE 
        WHEN f.Notes LIKE '%WRITTEN OFF%' THEN 'Written Off'
        WHEN f.Notes LIKE '%STOLEN%' THEN 'Stolen'
        WHEN f.Notes LIKE '%SOLD%' THEN 'Sold'
        WHEN f.Notes LIKE '%ACCIDENT%' THEN 'Out of Service'
        ELSE v.Status
    END,
    v.UpdatedAt = SYSUTCDATETIME()
FROM Vehicles v
INNER JOIN #Fleet f ON UPPER(LTRIM(RTRIM(v.RegistrationNumber))) = UPPER(LTRIM(RTRIM(f.Registration)));

DECLARE @updated INT = @@ROWCOUNT;
PRINT 'Vehicles updated with correct details: ' + CAST(@updated AS VARCHAR(10));

-- ═══════════════════════════════════════════════════════════════
-- 2) INSERT new vehicles not already in the DB
-- ═══════════════════════════════════════════════════════════════
INSERT INTO Vehicles (RegistrationNumber, VinNumber, Make, Model, Status, CreatedAt)
SELECT
    f.Registration,
    f.VinNumber,
    f.Make,
    f.Series,
    CASE 
        WHEN f.Notes LIKE '%WRITTEN OFF%' THEN 'Written Off'
        WHEN f.Notes LIKE '%STOLEN%' THEN 'Stolen'
        WHEN f.Notes LIKE '%SOLD%' THEN 'Sold'
        WHEN f.Notes LIKE '%ACCIDENT%' THEN 'Out of Service'
        ELSE 'Available'
    END,
    SYSUTCDATETIME()
FROM #Fleet f
WHERE NOT EXISTS (
    SELECT 1 FROM Vehicles v 
    WHERE UPPER(LTRIM(RTRIM(v.RegistrationNumber))) = UPPER(LTRIM(RTRIM(f.Registration)))
);

DECLARE @inserted INT = @@ROWCOUNT;
PRINT 'New vehicles inserted: ' + CAST(@inserted AS VARCHAR(10));

-- ═══════════════════════════════════════════════════════════════
-- 3) Decommission old vehicles NOT in spreadsheet
--    UNLESS they came from CarTrack sync or TFN sync
-- ═══════════════════════════════════════════════════════════════
UPDATE Vehicles SET
    Status = 'Decommissioned',
    UpdatedAt = SYSUTCDATETIME()
WHERE
    -- Not in the spreadsheet
    NOT EXISTS (
        SELECT 1 FROM #Fleet f 
        WHERE UPPER(LTRIM(RTRIM(f.Registration))) = UPPER(LTRIM(RTRIM(RegistrationNumber)))
    )
    -- Not from CarTrack
    AND (CarTrackId IS NULL OR CarTrackId = '')
    -- Not from TFN
    AND (IsLinkedToTfn = 0 OR IsLinkedToTfn IS NULL)
    -- Not already decommissioned
    AND Status != 'Decommissioned';

DECLARE @decommissioned INT = @@ROWCOUNT;
PRINT 'Old vehicles decommissioned (not in spreadsheet, not from CarTrack/TFN): ' + CAST(@decommissioned AS VARCHAR(10));

-- Summary
SELECT 
    Status, COUNT(*) AS Cnt 
FROM Vehicles 
GROUP BY Status 
ORDER BY Status;

SELECT COUNT(*) AS TotalVehiclesNow FROM Vehicles;

