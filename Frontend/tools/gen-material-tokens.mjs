// Generates src/styles/_material-tokens.scss: every Angular Material colour token that the
// prebuilt azure-blue theme hard-codes is re-pointed at the app's design tokens
// (src/styles/_tokens.scss), so Material components follow the Promed palette and dark mode.
//
// Run after upgrading @angular/material:  node tools/gen-material-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The package "exports" map hides prebuilt-themes from require.resolve, so read it by path.
const themePath = fileURLToPath(new URL('../node_modules/@angular/material/prebuilt-themes/azure-blue.css', import.meta.url));
const css = readFileSync(themePath, 'utf8');

// azure-blue hex -> design token
const MAP = {
  '#005cbb': 'var(--color-primary)',        // primary
  '#343dff': 'var(--color-primary)',        // tertiary / "accent": no violet in the brand
  '#00006e': 'var(--color-primary-hover)',
  '#d7e3ff': 'var(--color-primary-soft)',
  '#e0e0ff': 'var(--color-primary-soft)',
  '#ba1a1a': 'var(--color-danger)',
  '#1a1b1f': 'var(--color-text)',
  '#44474e': 'var(--color-text-2)',
  '#74777f': 'var(--color-text-3)',
  '#faf9fd': 'var(--color-surface)',
  '#e0e2ec': 'var(--color-line)',
  // typography: Material's components default to Roboto
  'roboto, sans-serif': 'var(--font-body)',
};

const out = [];
const ruleRe = /([^{}]+)\{([^{}]*)\}/g;
let m;
while ((m = ruleRe.exec(css))) {
  const selector = m[1].trim();
  if (selector.startsWith('@')) continue;
  const decls = [];
  for (const d of m[2].split(';')) {
    const i = d.indexOf(':');
    if (i < 0) continue;
    const prop = d.slice(0, i).trim();
    const value = d.slice(i + 1).trim().toLowerCase();
    if (prop.startsWith('--') && MAP[value]) decls.push(`  ${prop}: ${MAP[value]};`);
  }
  if (decls.length) out.push(`${selector} {\n${decls.join('\n')}\n}`);
}

const header = `// GENERATED by tools/gen-material-tokens.mjs from ${themePath.split(/[\\/]node_modules[\\/]/).pop()}.
// Do not edit by hand. Re-points Material's hard-coded theme colours at our tokens.
`;
writeFileSync(new URL('../src/styles/_material-tokens.scss', import.meta.url), header + out.join('\n\n') + '\n');
console.log(`wrote ${out.length} rules`);
